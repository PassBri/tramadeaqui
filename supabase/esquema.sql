-- =====================================================================
-- Nidito · esquema de base de datos para Supabase
-- Pega todo esto en Supabase → SQL Editor → Run.
-- La seguridad la ponen las políticas (RLS), no el código del sitio.
-- =====================================================================

-- ---------- Catálogo (público: solo lectura) ----------
create table if not exists categorias (
  id       text primary key,
  nombre   text not null,
  detalle  text,
  imagen   text,
  orden    int  default 0
);

create table if not exists catalogo (
  id          text primary key,
  nombre      text not null,
  categoria   text references categorias(id),
  precio      numeric not null,
  "precioAntes" numeric,
  stock       int default 0,
  destacado   boolean default false,
  nuevo       boolean default false,
  preventa    text,
  limitado    text,
  descripcion text,
  atributos   jsonb,
  variantes   jsonb,
  suavidad    int,
  humor       text,
  imagen      text
);

-- ---------- Pedidos (el cliente puede crear; NADIE los lee en público) ----------
create table if not exists pedidos (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz default now(),
  referencia  text unique,
  nombre      text,
  telefono    text,
  ciudad      text,
  direccion   text,
  nota        text,
  regalo      text,
  items       jsonb,
  subtotal    numeric,
  descuento   numeric,
  envio       numeric,
  total       numeric,
  codigo      text,
  estado      text default 'nuevo'
);

-- ---------- Mensajes de contacto (el visitante puede crear; privados) ----------
create table if not exists mensajes (
  id         bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  nombre     text,
  contacto   text,
  tipo       text,
  mensaje    text
);

-- ---------- Ajustes que la web lee en vivo (público: solo lectura) ----------
create table if not exists ajustes_publicos (
  clave text primary key,
  valor jsonb
);
insert into ajustes_publicos (clave, valor) values ('mostrarColeccion', 'true')
  on conflict (clave) do nothing;

-- =====================================================================
-- Políticas de seguridad (RLS)
-- =====================================================================
alter table categorias       enable row level security;
alter table catalogo         enable row level security;
alter table pedidos          enable row level security;
alter table mensajes         enable row level security;
alter table ajustes_publicos enable row level security;

-- Catálogo y ajustes: cualquiera puede LEER (lo necesita la tienda).
create policy "leer categorias" on categorias for select using (true);
create policy "leer catalogo"   on catalogo   for select using (true);
create policy "leer ajustes"    on ajustes_publicos for select using (true);

-- Pedidos y mensajes: cualquiera puede CREAR (checkout y contacto),
-- pero NADIE puede leerlos con la anon key. Así los datos del cliente quedan protegidos.
create policy "crear pedido"  on pedidos  for insert with check (true);
create policy "crear mensaje" on mensajes for insert with check (true);

